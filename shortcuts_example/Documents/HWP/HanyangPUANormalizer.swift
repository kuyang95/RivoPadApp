import Foundation

/// Converts the legacy Hanyang private-use Hangul syllables found in older HWP
/// documents into standard Unicode Hangul/Jamo. The packed interoperability
/// table is decoded locally; no Hancom or third-party runtime is linked.
nonisolated enum HanyangPUANormalizer {
    private struct MappingDescriptor {
        let source: UInt16
        let targetLength: Int
    }

    private struct Cursor {
        let data: Data
        var offset = 0

        mutating func readUInt16() -> UInt16? {
            guard offset + 2 <= data.count else { return nil }
            defer { offset += 2 }
            return UInt16(data[offset])
                | UInt16(data[offset + 1]) << 8
        }
    }

    private static let hanyangRange = UInt32(0xE0BC)...UInt32(0xF8F7)

    static func normalize(_ text: String) -> String {
        guard text.unicodeScalars.contains(where: {
            hanyangRange.contains($0.value)
        }) else {
            return text
        }

        var result = ""
        result.reserveCapacity(text.utf8.count)
        for scalar in text.unicodeScalars {
            if scalar.value <= UInt16.max,
               let replacement = mappings[UInt16(scalar.value)] {
                result.append(replacement)
            } else {
                result.unicodeScalars.append(scalar)
            }
        }
        // Hancom used the archaic arae-a spelling as its product wordmark.
        // Apple's Korean fallback fonts expose that sequence as separated
        // jamo, so use its modern readable spelling in ordinary document text.
        return result.replacingOccurrences(
            of: "ᄒᆞᆫ글",
            with: "한글"
        )
    }

    private static let mappings: [UInt16: String] = {
        guard let packed = Data(
            base64Encoded: packedMapping,
            options: .ignoreUnknownCharacters
        ) else {
            return [:]
        }
        return unpack(packed) ?? [:]
    }()

    /// Compact groups: count, (start,length) headers, per-code target lengths,
    /// then UTF-16LE target sequences.
    private static func unpack(_ data: Data) -> [UInt16: String]? {
        var cursor = Cursor(data: data)
        guard let rawGroupCount = cursor.readUInt16() else { return nil }
        let groupCount = Int(rawGroupCount)
        guard groupCount > 0, groupCount <= 256 else { return nil }

        var headers: [(start: UInt16, length: Int)] = []
        headers.reserveCapacity(groupCount)
        var mappingCount = 0
        for _ in 0..<groupCount {
            guard let start = cursor.readUInt16(),
                  let rawLength = cursor.readUInt16() else {
                return nil
            }
            let length = Int(rawLength)
            guard length > 0,
                  mappingCount <= 16_384 - length,
                  Int(start) + length - 1 <= Int(UInt16.max) else {
                return nil
            }
            headers.append((start, length))
            mappingCount += length
        }

        var descriptors: [MappingDescriptor] = []
        descriptors.reserveCapacity(mappingCount)
        for header in headers {
            for index in 0..<header.length {
                guard let rawTargetLength = cursor.readUInt16() else {
                    return nil
                }
                let targetLength = Int(rawTargetLength)
                // One legacy code point intentionally maps to an empty
                // sequence. Keep it in the table so it is removed instead of
                // leaking an unsupported private-use glyph into the viewer.
                guard targetLength <= 16 else {
                    return nil
                }
                descriptors.append(
                    MappingDescriptor(
                        source: header.start + UInt16(index),
                        targetLength: targetLength
                    )
                )
            }
        }

        var result: [UInt16: String] = [:]
        result.reserveCapacity(descriptors.count)
        for descriptor in descriptors {
            var units: [UInt16] = []
            units.reserveCapacity(descriptor.targetLength)
            for _ in 0..<descriptor.targetLength {
                guard let unit = cursor.readUInt16() else { return nil }
                units.append(unit)
            }
            result[descriptor.source] = String(decoding: units, as: UTF16.self)
        }
        guard cursor.offset == data.count else { return nil }
        return result
    }

